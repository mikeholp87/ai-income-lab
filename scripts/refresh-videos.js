import { existsSync } from 'node:fs';
import { readFile, writeFile } from 'node:fs/promises';
import { fetchUploads, sponsoredBenchmark, sponsoredVideos } from '../src/archive.js';
import { curatedSummary, withSummaries } from '../src/curated-summary.js';
import { topTools } from '../src/tools-page.js';
import { validFeed } from '../src/youtube.js';
import { refreshThumbnail } from './thumbnail.js';
import { syncWatchThumbnails } from './watch-thumbnails.js';

for (const file of ['.env.local', '.env']) {
  const path = `${import.meta.dirname}/../${file}`;
  if (existsSync(path)) process.loadEnvFile(path);
}

const path = new URL('../src/youtube-snapshot.json', import.meta.url);
try {
  const response = await fetch('https://www.ai-automation-station.com/api/youtube', { signal: AbortSignal.timeout(8000) });
  if (!response.ok) throw new Error(`HTTP ${response.status}`);
  const feed = await response.json();
  if (!validFeed(feed)) throw new Error('Invalid YouTube feed');
  // The feed drops the channel numbers when the YouTube API quota runs out; keep the last ones we had.
  const saved = JSON.parse(await readFile(path, 'utf8'));
  const channel = Number.isFinite(feed.channel?.subscribers) ? feed.channel : saved.channel;
  if (!Number.isFinite(channel?.subscribers)) throw new Error('Feed missing channel counts');
  await writeFile(path, `${JSON.stringify(withSummaries({ ...feed, channel }), null, 2)}\n`);
  console.log('Updated the latest-video snapshot.');
} catch (error) {
  if (!validFeed(JSON.parse(await readFile(path, 'utf8')))) throw new Error('No usable video snapshot', { cause: error });
  console.warn(`Using the saved video snapshot: ${error.message}`);
}

// Every upload, for /api/videos to serve while the YouTube API is unreachable. Keeps the saved copy on failure.
const uploadsPath = new URL('../src/uploads-snapshot.js', import.meta.url);
try {
  if (!process.env.YOUTUBE_API_KEY) throw new Error('YOUTUBE_API_KEY is not set');
  const uploads = await fetchUploads(process.env.YOUTUBE_API_KEY);
  if (!uploads.length) throw new Error('No public uploads returned');
  await writeFile(uploadsPath, `// Generated by scripts/refresh-videos.js on each build.\nexport const uploadsUpdatedAt = ${Date.now()};\nexport const uploads = [\n${uploads.map(video => JSON.stringify(video)).join(',\n')},\n];\n`);
  console.log(`Updated the uploads snapshot (${uploads.length} videos).`);
  // A description made only of links leaves no prose summary, so the page falls back to a generated line.
  const missing = uploads.filter(video => !video.summary && !curatedSummary(video));
  if (missing.length) console.warn(`No written summary for ${missing.length} videos (add one to src/video-summaries.js): ${missing.map(video => video.id).join(', ')}`);
  // The homepage's prerendered sponsored section; /api/videos?sponsored keeps it current between builds.
  const sponsored = sponsoredVideos(uploads);
  await writeFile(new URL('../src/sponsored-snapshot.json', import.meta.url), `${JSON.stringify(sponsored, null, 2)}\n`);
  await writeFile(new URL('../src/sponsor-benchmark.json', import.meta.url), `${JSON.stringify(sponsoredBenchmark(uploads), null, 2)}\n`);
  console.log(`Updated the sponsored snapshot (${sponsored.length} videos) and its views benchmark.`);
} catch (error) {
  console.warn(`Using the saved uploads snapshot: ${error.message}`);
}

try {
  await refreshThumbnail(JSON.parse(await readFile(path, 'utf8')).videos[0]);
  console.log('Updated the responsive hero thumbnail.');
} catch (error) {
  console.warn(`Using the saved hero thumbnail or YouTube fallback: ${error.message}`);
}

// Watch and archive thumbnails served from our own domain. Downloads only what is missing; the committed
// files are the cache, and a failure keeps the YouTube fallback for those videos.
try {
  const { uploads } = await import(`../src/uploads-snapshot.js?${Date.now()}`);
  const result = await syncWatchThumbnails(uploads.map(video => video.id));
  console.log(`Self-hosted thumbnails: ${result.total} videos, ${result.downloaded} new.`);
  if (result.failed.length) console.warn(`Thumbnail download failed for ${result.failed.length}: ${result.failed.join('; ')}`);
} catch (error) {
  console.warn(`Using the saved self-hosted thumbnails: ${error.message}`);
}

// The homepage's "Tools I use most" strip, counted the same way as the tools page, so the homepage bundle doesn't
// carry the video tool lists.
const { uploads } = await import(`../src/uploads-snapshot.js?${Date.now()}`);
await writeFile(new URL('../src/top-tools.json', import.meta.url), `${JSON.stringify(topTools(uploads), null, 2)}\n`);
